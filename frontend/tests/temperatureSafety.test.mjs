import test from 'node:test'
import assert from 'node:assert/strict'
import { ARTILLERY_PLA_BASIC, makeArtilleryPlaBasic } from '../src/profileLibrary.js'
import { checkArtilleryHeating } from '../src/temperatureSafety.js'

test('bundled Artillery PLA Basic provides explicitly safe default temperatures', () => {
  const source = { nozzle_temperature: [240], cool_plate_temp: [105], hot_plate_temp: [105], filament_type: ['ABS'] }
  const material = makeArtilleryPlaBasic(source)
  assert.equal(material.filament_type[0], 'PLA')
  assert.equal(material.nozzle_temperature[0], 205)
  assert.equal(material.nozzle_temperature_initial_layer[0], 210)
  for (const key of ['cool_plate_temp', 'eng_plate_temp', 'hot_plate_temp', 'textured_plate_temp',
    'cool_plate_temp_initial_layer', 'eng_plate_temp_initial_layer', 'hot_plate_temp_initial_layer', 'textured_plate_temp_initial_layer']) {
    assert.equal(material[key][0], 55, key)
  }
  assert.equal(source.nozzle_temperature[0], 240, 'upstream preset not mutated')
})

test('240 nozzle and 105 bed heater commands are blocked for Artillery PLA', () => {
  const gcode = '; generated by slicer\nM104 S240\nM140 S105\nM109 S240\nM190 R105\nG1 X10 Y10\n'
  const warnings = checkArtilleryHeating(gcode, ARTILLERY_PLA_BASIC)
  assert.ok(warnings.some(w => w.includes('M104') && w.includes('240')))
  assert.ok(warnings.some(w => w.includes('M190') && w.includes('105')))
  assert.ok(warnings.length >= 4)
})

test('safe PLA first-layer and other commands remain allowed', () => {
  const gcode = 'M140 S55\nM104 T0 S210\nM190 S55\nM109 S210\nG1 X10 Y10\nM104 S0\nM140 S0'
  assert.deepEqual(checkArtilleryHeating(gcode, ARTILLERY_PLA_BASIC), [])
  assert.deepEqual(checkArtilleryHeating('M104 S240\nM140 S105', 'ABS'), [])
})

test('GX metadata comments are also checked because the CLI copies them to the GX header', () => {
  const gcode = '; first_layer_bed_temperature = 105\n; nozzle_temperature = 240\n; layer_height = 0.2\nM104 S210\nM140 S55'
  const warnings = checkArtilleryHeating(gcode, ARTILLERY_PLA_BASIC)
  assert.equal(warnings.length, 2)
  assert.ok(warnings.some(w => w.includes('nozzle')))
  assert.ok(warnings.some(w => w.includes('bed')))
})

test('plain comments do not count as heater commands', () => {
  assert.deepEqual(checkArtilleryHeating('; M104 S240\n; A note about M140 S105\nM109 S0',
    ARTILLERY_PLA_BASIC), [])
})
